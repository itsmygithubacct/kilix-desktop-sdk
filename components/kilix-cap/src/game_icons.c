bool game_icon_valid(const uint8_t pixels[GAME_ICON_PIXELS])
{
    bool visible = false;
    if (pixels == NULL) return false;
    for (int i = 0; i < GAME_ICON_PIXELS; i++) {
        if (pixels[i] > 14u) return false;
        if (pixels[i] != 0u) visible = true;
    }
    return visible;
}

static void decode(const char *payload, uint8_t pixels[GAME_ICON_PIXELS])
{
    for (int i = 0; i < GAME_ICON_PIXELS; i++) {
        unsigned char ch = (unsigned char)payload[i];
        pixels[i] = ch <= '9' ? (uint8_t)(ch - '0')
                              : (uint8_t)(ch - 'a' + 10);
    }
}

static uint32_t id_hash(const char *text)
{
    uint32_t hash = 2166136261u;
    if (text == NULL) return hash;
    while (*text != '\0') {
        hash ^= (unsigned char)*text++;
        hash *= 16777619u;
    }
    return hash;
}

static void generic_icon(const char *id, uint8_t pixels[GAME_ICON_PIXELS])
{
    uint8_t accent = (uint8_t)(5u + id_hash(id) % 10u);
    memset(pixels, 0, GAME_ICON_PIXELS);
    /* A compact Kilix-95-style game window with a colored play arrow. */
    for (int y = 2; y <= 13; y++)
        for (int x = 1; x <= 14; x++)
            pixels[y * GAME_ICON_SIDE + x] =
                (x == 1 || x == 14 || y == 2 || y == 13) ? 1u : 4u;
    for (int x = 2; x <= 13; x++)
        pixels[3 * GAME_ICON_SIDE + x] = 10u;
    for (int y = 6; y <= 10; y++)
        for (int x = 6; x <= 6 + (y <= 8 ? y - 6 : 10 - y); x++)
            pixels[y * GAME_ICON_SIDE + x] = accent;
}

void game_icon_ensure(const char *game_id,
                      uint8_t pixels[GAME_ICON_PIXELS])
{
    if (pixels == NULL || game_icon_valid(pixels)) return;
    for (size_t i = 0; i < sizeof defaults / sizeof defaults[0]; i++)
        if (game_id != NULL && strcmp(defaults[i].id, game_id) == 0) {
            decode(defaults[i].payload, pixels);
            return;
        }
    generic_icon(game_id, pixels);
}
